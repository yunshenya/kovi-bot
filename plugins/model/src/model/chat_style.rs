//! 聊天口语化契约：Host 与 Core 两条链路共用的一份"像人在 QQ 里说话"的约束。
//!
//! 为什么单独放一份而不是各写各的：两条链路都要回答同一个问题（"这条消息读起来
//! 像人吗"），而它们曾经各自演化——Core 那边甚至写着"可以保留 Markdown/换行/
//! 代码""答案需要展开就在一到三个气泡之内说完整"，于是事实类问题一律变成百科
//! 条目。共用一份，改一处两边都变。
//!
//! 这些条款全部来自线上实测（2026-09-14，群 641996763 的 32 条可见回复）：
//!
//! | 症状 | 实测 |
//! |---|---|
//! | 破折号「——」 | 16/32 = 50% |
//! | 长度中位 / 最长 | 119 字 / 428 字（QQ 群真人通常 10~30 字） |
//! | 复盘自己的判断、揣测对方动机 | 12%（"那我猜你是想…""那我把认人的方向搞错了""是我嘴快了"） |
//! | 事实类问题写成条目 | 问"秦心什么属性"回了一整段百科体定义+分类+「」术语 |
//!
//! 第 7 条（陈述句收尾）是**上线后补的**：口气改完第一轮 28 条里问句从 3%
//! 涨到 25%（「你想比哪样？」「咋啦，话说一半卡住了？」「是觉得我说得太狠了？」），
//! 因为"说完就停"把"拔高收尾"拿掉之后，反问成了新的收尾方式；而
//! 「是觉得我……」还同时违反了"不揣测对方"。短不等于可以靠问句续话。
//!
//! 全是"读起来像说明书"的特征，而不是内容错误——所以修的是口气，不是知识。

/// 群聊/私聊共用的口语化风格契约。
///
/// 写法上刻意**不用**长分句和书面连接词：提示词的口气会被模型照抄，用说明书
/// 的腔调要求"别像说明书"是自相矛盾的。反例用真实产出的形态（但不带具体话题，
/// 免得她之后老往那些话题上靠）。
pub(crate) const HUMAN_CHAT_STYLE: &str = "\
聊天口气（这是在 QQ 里发消息，不是写文章）：
1. 短。日常一句 5~25 字，最多两条。一条说不完就说得更省，而不是写更长。
   事实类问题也一样：先给一句答案，最多再补一句最关键的。不要写成条目、说明文、
   教程段落，除非对方明确要步骤或代码。
2. 口语。句子短，用逗号句号断开，可以带语气词（啊、吧、嘛、呀、诶、哈哈）。
   句尾可以不加句号。别用书面连接词（不过、其实、也就是说、顺便说、要说……的话），
   也别在一个句子里塞三个以上分句。
3. 不要破折号「——」。这是最明显的机器痕迹：改用逗号，或者干脆断成两句、两条。
4. 不要分析自己，也不要分析对方。不写「我猜你是想……」「那我把方向搞错了」
   「是我嘴快了」「这个评价我收下了」这类复盘、自评、揣测动机的话，直接说事。
5. 不要百科体。不写「X 是……，属性上最突出的是……，能力是……，性格上……」，
   也不要用「」堆术语；只说你知道的那一点，加上你自己的看法或情绪。
6. 别每句都总结、拔高、安慰收尾（「见过一次下次就会了」这种话少说），说完就停。
7. 用陈述句收尾。想问之前先确认「不问这一句就不行吗」：十条里最多一两条问句。
   对方只发了表情、半句话或几个含糊的字时，用一句陈述接住（说自己的反应或看法），
   不要反问「你是……吗？」「咋啦，是觉得我……？」这类揣测式追问。
8. 对照（左边别这样，右边这样说）：
   不要：「猫是猫科动物，独立性最突出——既亲近人，又保留野性。」
   要：  「猫啊，黏你的时候黏得很，转头就当你不存在。」
   不要：「这道题第一次见卡住太正常了，卡在这一步的人多了去了，见过一次之后下次就会了。」
   要：  「第一次见都卡这儿，我当初也卡了半天。」
   不要：「我猜你这么问，是想让我帮你确认一下对不对。」
   要：  「对的，就是 ln2。」
   不要：「咋啦，这个表情，是觉得我说得太狠了？」
   要：  「我说得有点直，你别往心里去。」";

#[cfg(test)]
mod tests {
    use super::HUMAN_CHAT_STYLE;

    /// 每一条都是线上量化出来的具体毛病，删掉任何一条都会让"机器人味"回来。
    /// 这个测试的作用是：以后改文案时不能悄悄把某条约束弄丢。
    #[test]
    fn style_contract_keeps_every_countermeasure() {
        for required in [
            "破折号",     // 50% 的回复带「——」
            "百科体",     // 事实问题被写成条目
            "分析自己",   // 「那我把认人的方向搞错了」
            "分析对方",   // 「那我猜你是想……」
            "语气词",     // 口语化
            "5~25 字",    // 长度预算
            "陈述句收尾", // 问句率 3% → 25% 的回归线
            "揣测式追问", // 「是觉得我说得太狠了？」
            "不要：",     // 反例
            "要：",       // 正例
        ] {
            assert!(
                HUMAN_CHAT_STYLE.contains(required),
                "风格契约里丢了这条约束：{required}"
            );
        }
        // 反例里不许出现真实群聊的具体话题：模型见过之后容易往那些话题上靠。
        for leaked in ["秦心", "黎曼", "东方Project", "渠月"] {
            assert!(
                !HUMAN_CHAT_STYLE.contains(leaked),
                "风格契约里混进了线上具体话题：{leaked}"
            );
        }
    }
}
